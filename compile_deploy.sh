#!/bin/bash
set -euo pipefail

# ============================================================
# MicroPython compile + deploy tool
#
# Workflow:
#   1. Configure paths and targets on first run (or after moving this script)
#   2. Choose whether to compile all .py files first
#   3. Select the files to deploy
#   4. Stage, stop/release, transfer, restore monitoring; optionally reset
#
# Dependencies:
#   - python3 (local menu keyboard adapter)
#   - whiptail
#   - ssh
#   - scp
#   - mpy-cross
# ============================================================

ARCH="armv7emsp"

# ---------- helpers ----------------------------------------------------------

die() {
    echo "ERROR: $*" >&2
    exit 1
}

require_cmd() {
    command -v "$1" >/dev/null 2>&1 || die "'$1' is required but was not found."
}

input_box() {
    local title="$1"
    local prompt="$2"
    local default="$3"

    whiptail --title "$title" \
        --inputbox "$prompt" 10 80 "$default" \
        3>&1 1>&2 2>&3
}

yes_no() {
    local title="$1"
    local prompt="$2"

    whiptail --title "$title" \
        --yesno "$prompt" 10 80
}

# ---------- dependency checks -----------------------------------------------

case "${1:-}" in
    "") ;;
    --help|-h) echo "Usage: $0"; exit 0 ;;
    *) die "Usage: $0 (choose files interactively for every deployment)" ;;
esac
require_cmd python3
require_cmd whiptail
require_cmd ssh
require_cmd scp

# ---------- configuration ----------------------------------------------------

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# The script lives in the project root, so use its folder as the default.
PROJECT_DIR_DEFAULT="$SCRIPT_DIR"
SOURCE_DIR_DEFAULT="$SCRIPT_DIR"
OUTPUT_DIR_DEFAULT="$SCRIPT_DIR/MPY"
MPY_CROSS_DEFAULT="$SCRIPT_DIR/mpy-cross"
SSH_TARGET_DEFAULT="pi@raspberry.local"
MPREMOTE_DEFAULT="mpremote"

CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/serial-guardian"
CONFIG_FILE="$CONFIG_DIR/compile_deploy.conf"
CURRENT_SCRIPT_DIR="$SCRIPT_DIR"
GUARDIAN_URL="http://127.0.0.1:8080"
DEPLOY_WAIT="${GUARDIAN_DEPLOY_WAIT:-300}"
BOOT_WAIT="${GUARDIAN_BOOT_WAIT:-30}"
TRANSFER_WAIT="${GUARDIAN_TRANSFER_WAIT:-120}"

save_config() {
    mkdir -p "$CONFIG_DIR"
    local config_tmp
    config_tmp="$(mktemp "$CONFIG_DIR/.compile_deploy.XXXXXXXX")" || return $?
    {
        printf 'SCRIPT_DIR=%q\n' "$SCRIPT_DIR"
        printf 'SOURCE_DIR=%q\n' "$SOURCE_DIR"
        printf 'OUTPUT_DIR=%q\n' "$OUTPUT_DIR"
        printf 'MPY_CROSS=%q\n' "$MPY_CROSS"
        printf 'SSH_TARGET=%q\n' "$SSH_TARGET"
        printf 'MPREMOTE=%q\n' "$MPREMOTE"
        printf 'GUARDIAN_URL=%q\n' "$GUARDIAN_URL"
    } > "$config_tmp"
    mv -- "$config_tmp" "$CONFIG_FILE"
}

load_config() {
    [[ -f "$CONFIG_FILE" ]] || return 1
    # This file is generated by save_config and contains shell-quoted values.
    # shellcheck disable=SC1090
    source "$CONFIG_FILE"
    [[ -n "${SCRIPT_DIR:-}" && -n "${SOURCE_DIR:-}" && -n "${OUTPUT_DIR:-}" &&
        -n "${MPY_CROSS:-}" && -n "${SSH_TARGET:-}" && -n "${MPREMOTE:-}" ]]
}

configure_all() {
    local source_default="$SOURCE_DIR_DEFAULT"
    local output_default="$OUTPUT_DIR_DEFAULT"
    local mpy_cross_default="$MPY_CROSS_DEFAULT"
    local ssh_target_default="$SSH_TARGET_DEFAULT"
    local mpremote_default="$MPREMOTE_DEFAULT"

    SOURCE_DIR="$(input_box \
        "Source folder" \
        "Folder containing the .py files to compile:" \
        "$source_default")" || return 1

    OUTPUT_DIR="$(input_box \
        "Output folder" \
        "Folder where the compiled .mpy files will be written:" \
        "$output_default")" || return 1

    MPY_CROSS="$(input_box \
        "mpy-cross" \
        "Path to the mpy-cross executable:" \
        "$mpy_cross_default")" || return 1

    SSH_TARGET="$(input_box \
        "SSH target" \
        "Remote SSH target (user@host):" \
        "$ssh_target_default")" || return 1

    MPREMOTE="$(input_box \
        "mpy remote command" \
        "Remote mpremote executable/command:" \
        "$mpremote_default")" || return 1
}

if ! load_config || [[ "${SCRIPT_DIR:-}" != "$CURRENT_SCRIPT_DIR" ]]; then
    SCRIPT_DIR="$CURRENT_SCRIPT_DIR"
    configure_all || {
        echo "Cancelled."
        exit 0
    }
    [[ -d "$SOURCE_DIR" ]] || die "Source directory does not exist: $SOURCE_DIR"
    [[ -x "$MPY_CROSS" ]] || die "mpy-cross is missing or not executable: $MPY_CROSS"
    save_config
else
    SCRIPT_DIR="$CURRENT_SCRIPT_DIR"
    [[ -d "$SOURCE_DIR" ]] || die "Source directory does not exist: $SOURCE_DIR"
    [[ -x "$MPY_CROSS" ]] || die "mpy-cross is missing or not executable: $MPY_CROSS"
fi

mkdir -p "$OUTPUT_DIR"

# ---------- build / deployment ------------------------------------------------

compile_all() (
    # A compiler error leaves the previous build intact and touches no device.
    local build py_file name
    build="$(mktemp -d "$OUTPUT_DIR/.compile.XXXXXXXX")" || exit $?
    trap 'rm -rf -- "$build"' EXIT
    mapfile -d '' sources < <(find "$SOURCE_DIR" -maxdepth 1 -type f -name '*.py' -print0 | sort -z)
    (( ${#sources[@]} )) || die "No .py files directly in $SOURCE_DIR"
    echo "Compiling ${#sources[@]} module(s) ($ARCH)…"
    for py_file in "${sources[@]}"; do
        name="$(basename "$py_file" .py)"
        echo "  $name.py"
        "$MPY_CROSS" -march="$ARCH" "$py_file" -o "$build/$name.mpy" || exit $?
        [[ -f "$build/$name.mpy" ]] || die "Compiler produced no output for $name.py"
    done
    find "$OUTPUT_DIR" -maxdepth 1 -type f -name '*.mpy' -delete || exit $?
    cp -- "$build/"*.mpy "$OUTPUT_DIR/"
)

quote_command() {
    local arg
    for arg in "$@"; do printf "'%s' " "${arg//\'/\'\\\'\'}"; done
}

choose_files() {
    local full_path filename choices
    mapfile -d '' MPY_FILES < <(find "$OUTPUT_DIR" -maxdepth 1 -type f -name '*.mpy' -print0 | sort -z)
    (( ${#MPY_FILES[@]} )) || { echo "No compiled .mpy files found."; return 1; }
    OPTIONS=()
    for full_path in "${MPY_FILES[@]}"; do
        filename="$(basename "$full_path")"
        [[ "$filename" != *$'\n'* ]] || die "Newlines in filenames are unsupported"
        OPTIONS+=("$filename" "" "OFF")
    done
    choices="$(whiptail --title "Deploy and watch" --separate-output --checklist \
        "Select modules to deploy:" 20 80 12 "${OPTIONS[@]}" 3>&1 1>&2 2>&3)" || return 1
    [[ -n "$choices" ]] || return 1
    mapfile -t SELECTED_FILES <<< "$choices"
}

# Embedded coordinator runs directly via SSH's command channel. No helper
# file is created or copied to the Pi; SCP transfers only selected modules.
write_deploy_helper() {
    cat <<'GUARDIAN_DEPLOY_PY'
#!/usr/bin/env python3
"""Short-lived deployment coordinator, staged on the Pi by compile_deploy.sh."""
import argparse
import fcntl
import json
import math
import os
from pathlib import Path
import shlex
import shutil
import signal
import subprocess
import sys
import time
import urllib.request
import urllib.error


class DeploymentError(RuntimeError):
    pass


class Guardian:
    def __init__(self, url):
        self.url = url.rstrip('/')

    def call(self, path, post=False):
        req = urllib.request.Request(self.url + path, data=b'{}' if post else None,
                                     headers={'Content-Type': 'application/json'})
        with urllib.request.urlopen(req, timeout=5) as response:
            return json.load(response)

    def status(self):
        try:
            return self.call('/api/status')
        except urllib.error.HTTPError as exc:
            if exc.code == 404:
                raise DeploymentError('Update and restart Serial Guardian on the Pi first (/api/status unavailable)') from exc
            raise


def wait_for(guardian, predicate, timeout, description):
    started = time.monotonic()
    deadline = started + timeout
    tick, next_report = 0, started
    while True:
        state = guardian.status()
        elapsed = time.monotonic() - started
        if predicate(state):
            print(('\r\033[K' if sys.stdout.isatty() else '') + '[ok] {} ({:.1f}s)'.format(description, elapsed), flush=True)
            return state
        if time.monotonic() >= deadline:
            if sys.stdout.isatty(): print('\r\033[K', end='', flush=True)
            raise DeploymentError('Timed out: ' + description)
        if sys.stdout.isatty() or time.monotonic() >= next_report:
            detail = 'connected' if state['connected'] else 'waiting for USB'
            if not state['monitoring']: detail += ' / monitor paused'
            if state.get('stop_armed'): detail += ' / Stop armed'
            message = '[{}] {} | {:.0f}/{:.0f}s | {}'.format('|/-\\'[tick % 4], description.split(' (')[0], elapsed, timeout, detail)
            if sys.stdout.isatty(): message = message[:max(20, shutil.get_terminal_size().columns-1)]
            print(('\r\033[K' if sys.stdout.isatty() else '') + message,
                  end='' if sys.stdout.isatty() else '\n', flush=True)
            tick += 1
            next_report = time.monotonic() + 5
        time.sleep(0.25)


def deploy(guardian, files, mpremote, wait=300, boot_wait=30, transfer_wait=120, reset=True):
    command = shlex.split(mpremote)
    if not command or not shutil.which(command[0]):
        raise DeploymentError('mpremote executable not found on the Pi: ' + mpremote)
    if not files or any(not Path(path).is_file() for path in files):
        raise DeploymentError('Staged deployment files are missing')
    state = guardian.status()  # Fail before stopping anything if Guardian is outdated.
    required = {'serial_port', 'serial_open', 'boot_count', 'halted', 'monitoring', 'stop_armed'}
    if not required <= state.keys():
        raise DeploymentError('Update and restart Serial Guardian on the Pi first')
    port = state['serial_port']
    def released(s):
        return not s['monitoring'] and not s['serial_open'] and not s['connected']

    if released(state):
        # A user may already have stopped the board and paused Guardian.
        # mpremote's raw-REPL entry will interrupt the board before copying.
        print('Monitoring already paused; serial port is released.', flush=True)
    else:
        print('Waiting for device wake / Stop to take effect…', flush=True)
        stop_count = state.get('stop_count', 0)
        if not state['monitoring']:
            state = guardian.call('/api/monitoring/resume', post=True)
        # Stop and Pause are toggles. Never blindly retry them. A connected
        # Stop can complete in this response and disappear before the next GET.
        if not state['halted'] and not state['stop_armed']:
            state = guardian.call('/api/stop', post=True)
        if not state['halted'] and not released(state) and state.get('stop_count', 0) <= stop_count:
            state = wait_for(guardian, lambda s: s['halted'] or released(s)
                             or s.get('stop_count', 0) > stop_count, wait, 'device Stop')
        print('Stop acknowledged. Releasing the serial port…', flush=True)
        if state['monitoring'] and not state.get('pause_pending'):
            guardian.call('/api/monitoring/pause', post=True)
        wait_for(guardian, released, wait, 'serial port release')
    print('Serial port released. Transferring {} file(s)…'.format(len(files)), flush=True)
    # A single mpremote connection, explicit port, no implicit soft reboot.
    # A partial/failed transfer raises before any resume or reset request.
    subprocess.run(command + ['connect', port, 'resume', 'fs', 'cp'] + list(files) + [':'],
                   check=True, timeout=transfer_wait)
    print('Transfer complete. Restoring monitoring…', flush=True)
    guardian.call('/api/monitoring/resume', post=True)
    state = wait_for(guardian, lambda s: s['monitoring'] and s['connected'] and s['serial_open'],
                     wait, 'monitor reconnect')
    if not reset:
        print('Monitoring restored. Device left at the REPL; use Reset in Guardian when ready.', flush=True)
        return
    baseline = state['boot_count']
    guardian.call('/api/device/reset', post=True)
    print('Reset requested. Waiting for the configured boot marker…', flush=True)
    wait_for(guardian, lambda s: s['boot_count'] > baseline, boot_wait, 'boot marker (files transferred; inspect Live)')
    print('Boot detected. Watch the Guardian Live dashboard.', flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--url', default='http://127.0.0.1:8080')
    parser.add_argument('--mpremote', default='mpremote')
    parser.add_argument('--wait', type=float, default=300)
    parser.add_argument('--boot-wait', type=float, default=30)
    parser.add_argument('--transfer-wait', type=float, default=120)
    parser.add_argument('--no-reset', action='store_true', help='restore monitoring but leave the board at the REPL')
    parser.add_argument('files', nargs='+')
    args = parser.parse_args()
    if any(not math.isfinite(value) or value <= 0 for value in (args.wait, args.boot_wait, args.transfer_wait)):
        parser.error('timeouts must be positive')
    def cancel(signum, frame):
        raise KeyboardInterrupt

    # The SSH session has a PTY: Ctrl+C interrupts us, and disconnection sends
    # SIGHUP. Both unwind subprocess.run and this lock instead of orphaning us.
    signal.signal(signal.SIGHUP, cancel)
    signal.signal(signal.SIGTERM, cancel)
    # Serialize cooperating deploy invocations on this Pi, including different
    # staging directories. The advisory lock is released on every exit path.
    with open('/tmp/serial-guardian-deploy.lock', 'a+') as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            lock.seek(0)
            owner = lock.read().strip() or 'unknown (older coordinator)'
            print('Another deployment is running on this Pi. Lock owner: {}. '
                  'Inspect its process before cancelling it; do not delete the lock file.'.format(owner), file=sys.stderr)
            return 1
        lock.seek(0)
        lock.truncate()
        lock.write('PID ' + str(os.getpid()))
        lock.flush()
        try:
            deploy(Guardian(args.url), args.files, args.mpremote,
                   args.wait, args.boot_wait, args.transfer_wait, reset=not args.no_reset)
        except (Exception, KeyboardInterrupt) as exc:
            print('\nDeployment stopped: {}\nNo further reset/resume will be attempted. '
                  'If transfer failed, leave the device halted and retry; '
                  'a pending Stop may need cancellation in the dashboard.'.format(exc), file=sys.stderr)
            return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
GUARDIAN_DEPLOY_PY
}

deploy_files() (
    local filename stage remote_command coordinator
    local -a local_files=() remote_files=() reset_args=()
    if [[ "$RESET_AFTER" == 0 ]]; then reset_args=(--no-reset); fi
    [[ "$SSH_TARGET" != -* ]] || die "Invalid SSH target"
    for filename in "${SELECTED_FILES[@]}"; do
        [[ "$filename" != */* && "$filename" != -* && "$filename" != *$'\n'* && "$filename" == *.mpy ]] || die "Invalid module filename"
        [[ -f "$OUTPUT_DIR/$filename" ]] || die "Missing compiled file: $filename; select files again."
        local_files+=("$OUTPUT_DIR/$filename")
    done
    (( ${#local_files[@]} )) || die "No files selected"
    echo "Staging ${#local_files[@]} file(s) on $SSH_TARGET…"
    stage="$(ssh -o ConnectTimeout=10 -- "$SSH_TARGET" 'mktemp -d /tmp/serial-guardian-deploy.XXXXXXXX')" || exit $?
    [[ "$stage" =~ ^/tmp/serial-guardian-deploy\.[A-Za-z0-9]+$ ]] || die "Invalid staging directory returned by SSH"
    trap 'ssh -o ConnectTimeout=10 -- "$SSH_TARGET" "rm -rf -- $stage" </dev/null || true' EXIT
    scp -- "${local_files[@]}" "$SSH_TARGET:$stage/" || exit $?
    for filename in "${SELECTED_FILES[@]}"; do remote_files+=("$stage/$filename"); done
    coordinator="$(write_deploy_helper)"
    remote_command="$(quote_command python3 -c "$coordinator" --url "$GUARDIAN_URL" \
        --mpremote "$MPREMOTE" --wait "$DEPLOY_WAIT" --boot-wait "$BOOT_WAIT" \
        --transfer-wait "$TRANSFER_WAIT" "${reset_args[@]}" -- "${remote_files[@]}")"
    # A remote PTY forwards Ctrl+C and sends SIGHUP if SSH disconnects.
    ssh -tt -- "$SSH_TARGET" "$remote_command"
)

# ---------- main menu --------------------------------------------------------

RESET_AFTER=1
MENU_DEFAULT=1

# Translate numeric shortcuts to native Home/Down keys inside an otherwise
# unchanged whiptail dialog. The chosen tag still comes from whiptail itself.
number_menu() {
    python3 -c "$(cat <<'NUMBER_MENU_PY'
import errno, fcntl, os, pty, select, signal, struct, subprocess, sys, termios, tty
if not sys.stdin.isatty():
    result = subprocess.run(sys.argv[1:], stderr=subprocess.PIPE)
    sys.stdout.buffer.write(result.stderr)
    sys.exit(result.returncode)
terminal = os.open('/dev/tty', os.O_RDWR)
master, slave = pty.openpty()
def resize(*args):
    size = fcntl.ioctl(terminal, termios.TIOCGWINSZ, b'\0' * 8)
    fcntl.ioctl(master, termios.TIOCSWINSZ, size)
def setup():
    os.setsid()
    fcntl.ioctl(0, termios.TIOCSCTTY, 0)
resize()
old = termios.tcgetattr(terminal)
process = None
try:
    process = subprocess.Popen(sys.argv[1:], stdin=slave, stdout=slave,
                               stderr=subprocess.PIPE, preexec_fn=setup)
    os.close(slave)
    tty.setraw(terminal)
    signal.signal(signal.SIGWINCH, resize)
    shortcuts = {ord(key): index for index, key in enumerate('123456')}
    escape = bytearray()
    mouse_bytes = 0
    while process.poll() is None:
        readable, _, _ = select.select([master, terminal], [], [], .1)
        for fd in readable:
            if fd == master:
                try: data = os.read(master, 65536)
                except OSError as error:
                    if error.errno == errno.EIO: continue
                    raise
                os.write(terminal, data)
            else:
                data = os.read(terminal, 512)
                if not data:
                    process.terminate(); break
                for key in data:
                    if mouse_bytes:
                        os.write(master, bytes([key])); mouse_bytes -= 1
                    elif escape:
                        escape.append(key)
                        if len(escape) == 2 and key not in b'[O' or len(escape) >= 3 and 0x40 <= key <= 0x7e:
                            os.write(master, escape)
                            if escape == b'\x1b[M': mouse_bytes = 3
                            escape.clear()
                    elif key == 27:
                        escape.append(key)
                    elif key in shortcuts:
                        os.write(master, b'\x1b[H' + b'\x1b[B' * shortcuts[key] + b'\r')
                    else:
                        os.write(master, bytes([key]))
        # Standalone Escape must reach whiptail as well as escape sequences.
        if escape and not select.select([terminal], [], [], .05)[0]:
            os.write(master, escape); escape.clear()
    sys.stdout.buffer.write(process.stderr.read())
    sys.exit(process.wait() if process.returncode >= 0 else 128-process.returncode)
finally:
    termios.tcsetattr(terminal, termios.TCSADRAIN, old)
    os.close(terminal); os.close(master)
    if process is not None and process.poll() is None:
        process.terminate(); process.wait()
NUMBER_MENU_PY
)" "$@"
}

main_menu() {
    local reset_mark='[x]'
    if [[ "$RESET_AFTER" == 0 ]]; then reset_mark='[ ]'; fi
    # The adapter emits the chosen tag on stdout; do not apply whiptail's
    # usual stderr/stdout swap here or the shell loses the selection.
    number_menu whiptail --title "MicroPython Compile / Deploy" --default-item "$MENU_DEFAULT" \
        --menu "Press 1-6 to activate immediately. Arrows + Enter also work. 6 toggles Reset." 18 85 6 \
        "1" "Compile all and deploy selected files" \
        "2" "Deploy selected built files" \
        "3" "Compile all .py files" \
        "4" "Settings" \
        "5" "Exit" \
        "6" "$reset_mark Reset device after transfer"
}

while true; do
    MENU_CHOICE="$(main_menu)" || exit 0
    MENU_DEFAULT=1
    case "$MENU_CHOICE" in
        6)
            if [[ "$RESET_AFTER" == 1 ]]; then RESET_AFTER=0; else RESET_AFTER=1; fi
            MENU_DEFAULT=6
            ;;
        3)
            if compile_all; then echo "Compile complete."; exit 0
            else echo "Compilation failed; previous build retained." >&2; exit 1; fi
            ;;
        1|2)
            if [[ "$MENU_CHOICE" == 1 ]]; then
                compile_all || { echo "Compilation failed; device untouched." >&2; exit 1; }
            fi
            choose_files || exit 0
            if deploy_files; then
                echo "Deployment complete."
                exit 0
            else
                echo "Deployment stopped. Inspect Guardian before resuming the device." >&2
                exit 1
            fi
            ;;
        4)
            SOURCE_DIR_NEW="$(
                input_box \
                    "Source folder" \
                    "Folder containing the .py files:" \
                    "$SOURCE_DIR"
            )" || continue

            OUTPUT_DIR_NEW="$(
                input_box \
                    "Output folder" \
                    "Folder where .mpy files are written:" \
                    "$OUTPUT_DIR"
            )" || continue

            MPY_CROSS_NEW="$(
                input_box \
                    "mpy-cross" \
                    "Path to the mpy-cross executable:" \
                    "$MPY_CROSS"
            )" || continue

            [[ -d "$SOURCE_DIR_NEW" ]] || {
                whiptail --title "Invalid source folder" \
                    --msgbox "Directory does not exist:\n$SOURCE_DIR_NEW" 8 70
                continue
            }

            [[ -x "$MPY_CROSS_NEW" ]] || {
                whiptail --title "Invalid mpy-cross" \
                    --msgbox "Not executable:\n$MPY_CROSS_NEW" 8 70
                continue
            }

            SSH_TARGET_NEW="$(
                input_box \
                    "SSH target" \
                    "Remote SSH target (user@host):" \
                    "$SSH_TARGET"
            )" || continue

            MPREMOTE_NEW="$(
                input_box \
                    "mpy remote command" \
                    "Remote mpremote executable/command:" \
                    "$MPREMOTE"
            )" || continue

            GUARDIAN_URL_NEW="$(input_box "Guardian on the Pi" \
                "Guardian URL as reached from the Pi itself:" "$GUARDIAN_URL")" || continue
            SOURCE_DIR="$SOURCE_DIR_NEW"
            OUTPUT_DIR="$OUTPUT_DIR_NEW"
            MPY_CROSS="$MPY_CROSS_NEW"
            SSH_TARGET="$SSH_TARGET_NEW"
            MPREMOTE="$MPREMOTE_NEW"
            GUARDIAN_URL="$GUARDIAN_URL_NEW"
            mkdir -p "$OUTPUT_DIR"
            save_config
            ;;

        5)
            exit 0
            ;;
    esac
done
